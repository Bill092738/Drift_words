-- | Writes the TypeScript declarations for "Drift.Protocol".
--
-- Usage: drift-gen-ts OUTPUT_FILE
module Main (main) where

import Data.Aeson.TypeScript.TH
  ( FormattingOptions (..)
  , ExportMode (..)
  , defaultFormattingOptions
  , formatTSDeclarations'
  , getTypeScriptDeclarations
  )
import Data.Proxy (Proxy (..))
import Drift.Protocol
import System.Environment (getArgs)
import System.Exit (die)

main :: IO ()
main = do
  args <- getArgs
  out <- case args of
    [path] -> pure path
    _ -> die "usage: drift-gen-ts OUTPUT_FILE"
  writeFile out (header <> formatTSDeclarations' formatting declarations <> "\n")
  where
    formatting = defaultFormattingOptions {exportMode = ExportEach}
    declarations =
      concat
        [ getTypeScriptDeclarations (Proxy :: Proxy NodeId)
        , getTypeScriptDeclarations (Proxy :: Proxy CandidateId)
        , getTypeScriptDeclarations (Proxy :: Proxy SourceId)
        , getTypeScriptDeclarations (Proxy :: Proxy EntryId)
        , getTypeScriptDeclarations (Proxy :: Proxy Lang)
        , getTypeScriptDeclarations (Proxy :: Proxy Vec2)
        , getTypeScriptDeclarations (Proxy :: Proxy Candidate)
        , getTypeScriptDeclarations (Proxy :: Proxy Origin)
        , getTypeScriptDeclarations (Proxy :: Proxy SourceKind)
        , getTypeScriptDeclarations (Proxy :: Proxy Source)
        , getTypeScriptDeclarations (Proxy :: Proxy Entry)
        , getTypeScriptDeclarations (Proxy :: Proxy Outputs)
        , getTypeScriptDeclarations (Proxy :: Proxy Command)
        , getTypeScriptDeclarations (Proxy :: Proxy ClientMsg)
        , getTypeScriptDeclarations (Proxy :: Proxy Event)
        , getTypeScriptDeclarations (Proxy :: Proxy Stamped)
        , getTypeScriptDeclarations (Proxy :: Proxy DiagnosticLevel)
        , getTypeScriptDeclarations (Proxy :: Proxy ServerMsg)
        ]
    header =
      unlines
        [ "// GENERATED by backend/app/GenTs.hs from backend/src/Drift/Protocol.hs."
        , "// Do not edit by hand. Regenerate with: make protocol"
        , "/* eslint-disable */"
        , ""
        ]
